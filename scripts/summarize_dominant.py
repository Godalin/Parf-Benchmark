import os
import re
import argparse
import csv

def count_alarms(filename, directory):
    """
    Count alarms and extract analysis time in the specified file in the given directory.

    Args:
        filename (str): The name of the log file.
        directory (str): The directory containing the log file.

    Returns:
        tuple: A tuple containing a list of alarms and a list of analysis times.
    """
    alarm_pattern = re.compile(r'\b(\d+) (alarm[s]?) generated by the analysis')
    time_pattern_1 = re.compile(r'^real\s+(\d+m[\d.]+s)')
    time_pattern_2 = re.compile(r'(\d+:\d+\.\d+)elapsed')

    total_alarms = []
    times = []

    try:
        with open(os.path.join(directory, filename), 'r') as file:
            for line in file:
                match = alarm_pattern.search(line)
                if match:
                    total_alarms.append(int(match.group(1)))
                match = time_pattern_1.search(line) or time_pattern_2.search(line)
                if match:
                    times.append(match.group(1))
    except FileNotFoundError:
        print(f"File {filename} not found in {directory}")

    return total_alarms, times

def analyze_project_logs(project_dir, project_name, output_data):
    """
    Analyze all log files in the specified project's results directory and add to output data.

    Args:
        project_dir (str): Path to the parent project directory.
        project_name (str): Name of the project (subdirectory containing logs).
        output_data (list): A list to store the summary data for all projects.
    """
    # Define the path to the results directory
    results_dir = os.path.join(project_dir, project_name, ".frama-c", "dominant_params_results")

    if not os.path.isdir(results_dir):
        print(f"Warning: Results directory {results_dir} does not exist, skipping project {project_name}.")
        return

    # Traverse all log files in the results directory
    for log_file in os.listdir(results_dir):
        if log_file.endswith(".log"):
            alarms, times = count_alarms(log_file, results_dir)

            # Prepare the row for this log file
            total_alarms = sum(alarms) if alarms else "N/A"
            total_time = ", ".join(times) if times else "N/A"

            output_data.append((project_name, log_file, total_alarms, total_time))

def analyze_logs(project_dir, output_dir):
    """
    Analyze all projects in the specified directory and generate a summary table.

    Args:
        project_dir (str): Path to the directory containing multiple projects.
        output_dir (str): Directory where the output summary will be saved.
    """
    # Prepare output data
    summary_data = [("Project", "Analysis", "Alarms", "Time")]

    # Traverse all projects in the project directory
    for project_name in os.listdir(project_dir):
        project_path = os.path.join(project_dir, project_name)
        if os.path.isdir(project_path):
            analyze_project_logs(project_dir, project_name, summary_data)

    # Write the summary table to a CSV file
    os.makedirs(output_dir, exist_ok=True)
    # output_file = os.path.join(output_dir, "summary_table.csv")
    output_file = os.path.join(output_dir, "summary_table_precision0.csv")

    try:
        with open(output_file, 'w', newline='') as csvfile:
            writer = csv.writer(csvfile)
            writer.writerows(summary_data)
        print(f"Summary table saved to {output_file}")
    except Exception as e:
        print(f"Error writing summary table: {e}")

def main():
    # Set up argument parser
    parser = argparse.ArgumentParser(description="Analyze static analysis log files from multiple projects and generate a summary table.")
    parser.add_argument("project_dir", type=str, help="Path to the directory containing multiple projects.")
    parser.add_argument("output_dir", type=str, help="Directory where the output summary will be saved.")
    args = parser.parse_args()

    # Run the analysis
    analyze_logs(args.project_dir, args.output_dir)

if __name__ == "__main__":
    main()
