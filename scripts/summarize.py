def count_alarms(filename, directory):  
    """  
    Count alarms in the specified file in the given directory.  
    """  
    alarm_pattern = re.compile(r'(\d+) (alarm[s]?) generated by the analysis')
    time_pattern_1 = re.compile(r'^real\s+(\d+m[\d.]+s)')
    time_pattern_2 = re.compile(r'(\d+:\d{2}:\d{2}|\d+:\d{2}\.\d{2})elapsed')
    total_alarms = [] 
    times = []
      
    try:  
        with open(os.path.join(directory, filename), 'r') as file:  
            for line in file:  
                match = alarm_pattern.search(line)  
                if match:  
                    total_alarms.append(int(match.group(1))) 
                match = time_pattern_1.search(line) or time_pattern_2.search(line)
                if match:
                    times.append(match.group(1))
    except FileNotFoundError:  
        print(f"File {filename} not found in {directory}")  
      
    return total_alarms, times
  
def generate_single_eva_summary(root_dir, filename):  
    """  
    Main function to process the directories and files.  
    """  
    summary_file = f"{filename}-summary.txt"
    with open(summary_file, 'w') as summary:  
        for subdir, dirs, files in os.walk(root_dir):  
            frama_c_dir = os.path.join(subdir, '.frama-c')  
            if os.path.isdir(frama_c_dir):  
                alarms, times = count_alarms(filename, frama_c_dir)
                subdir = subdir[len(root_dir)+1:]
                if len(alarms) == 1:
                    for num, time in zip(alarms, times):
                        summary.write(f"{subdir}, Alarms: {num}, Time: {time_to_seconds(time)}s\n")
                else:
                    index = 1
                    for num, time in zip(alarms, times):
                        summary.write(f"{subdir}-ex{index}, Alarms: {num}, Time: {time_to_seconds(time)}s\n")
                        index += 1
  
    print(f"Summary has been written to {summary_file}")

