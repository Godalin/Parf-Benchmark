def extract_info(file_path):  
    """    
    Extracts <parameters> and alarms number of most accurate analysis from given file.
    """  
    parameters = None  
    alarm_count = 0  
    in_alarms_section = False  
    info_list = []
    time_pattern_1 = re.compile(r'^real\s+(\d+m[\d.]+s)')
    time_pattern_2 = re.compile(r'(\d+:\d{2}:\d{2}|\d+:\d{2}\.\d{2})elapsed')

    with open(file_path, 'r') as file:  
        for line in file:  
            if '[parf] Final parameter:' in line:  
                parameters = line.split(':')[-1].strip()  
                in_alarms_section = True  # counting alarms after finding 'Final parameter'
            elif in_alarms_section:
                if '[parf] alarm (' in line:
                    alarm_count += 1
                elif time_pattern_1.search(line) or time_pattern_2.search(line):
                    match = time_pattern_1.search(line) or time_pattern_2.search(line)
                    info_list.append((parameters, alarm_count, match.group(1)))
                    alarm_count = 0
                    in_alarms_section = False
    # print(f"in_alarms_section: {in_alarms_section}")
    return info_list  
  
def generate_parf_summary(root_dir, filename):  
    """
    Tranverse all the subdirectories of root_dir and make summaries.
    """  
    summaries = []
    for subdir, dirs, files in os.walk(root_dir):
        if '.frama-c' in dirs:  
            # print(f"Searching {subdir}")
            frama_c_dir = os.path.join(subdir, '.frama-c')
            file_path = os.path.join(frama_c_dir, filename)
            if os.path.exists(file_path):
                # print(f"Inspecting {file_path}")
                info_list = extract_info(file_path)
                subdir = subdir[len(root_dir)+1:]
                if len(info_list) == 1:
                    # print(f"Inspecting2 {file_path}")
                    for (parameters, alarm_count, time) in info_list:
                        summaries.append(f"{subdir}, Alarms: {alarm_count}, Time: {time_to_seconds(time)}s, Parameters: {parameters}\n") 
                else:
                    index = 1
                    for (parameters, alarm_count, time) in info_list:
                        summaries.append(f"{subdir}-ex{index}, Alarms: {alarm_count}, Time: {time_to_seconds(time)}s, Parameters: {parameters}\n")  
                        index += 1
                    # print(f"Index: {index}")
  
    # generates summaries
    summary_filename = f"{filename}-summary.txt"  
    with open(summary_filename, 'w') as summary_file:  
        summary_file.writelines(summaries)  

