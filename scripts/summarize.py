import os  
import sys
import re

def time_to_seconds(time_str): 
    parts = time_str.split(':') if ':' in time_str  else time_str.replace('s', '').split('m')  
       
    minutes = int(parts[0])   
    if len(parts) > 1:  
        seconds_fraction = float(parts[1])
    else:  
        seconds_fraction = 0  
      
    total_seconds = minutes * 60 + seconds_fraction 
    total_seconds_rounded = round(total_seconds)  
    return total_seconds_rounded

