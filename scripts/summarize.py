def time_to_seconds(time_str):
    # Patterns for different time formats
    patterns = [
        (re.compile(r'(?:(\d+)m)?(?:(\d+(?:\.\d+)?)s)?'), "XmY.Zs format"),
        (re.compile(r'(?:(\d+):)?(\d+):(\d+(?:\.\d+)?)'), "H:M:S format"),
        (re.compile(r'(\d+):(\d+(?:\.\d+)?)'), "M:S.Z format")
    ]

    for pattern, desc in patterns:
        match = pattern.fullmatch(time_str)
        if match:
            if desc == "XmY.Zs format":
                minutes = int(match.group(1)) if match.group(1) else 0
                seconds = float(match.group(2)) if match.group(2) else 0
            elif desc == "H:M:S format":
                hours = int(match.group(1)) if match.group(1) else 0
                minutes = int(match.group(2))
                seconds = float(match.group(3))
                return int(hours * 3600 + minutes * 60 + seconds)
            elif desc == "M:S.Z format":
                minutes = int(match.group(1))
                seconds = float(match.group(2))
            return int(minutes * 60 + seconds)
    raise ValueError(f"Invalid time format: {time_str}")

